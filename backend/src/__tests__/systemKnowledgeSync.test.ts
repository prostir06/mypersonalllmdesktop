process.env.DATABASE_URL =
  process.env.DATABASE_URL || 'postgresql://mock:mock@localhost:5432/mock_db';

import {
  buildIntrospectedKnowledgeCatalog,
  computeVersionHash,
} from '../services/systemKnowledge/introspector';
import { getLiveSystemMetadata } from '../services/systemKnowledge/liveMetadata';
import { getCuratedKnowledgeCards } from '../services/systemKnowledge/registry';
import {
  ALLOWED_PROVIDERS,
  ALLOWED_SETTINGS_FIELDS,
  MIN_TEMPERATURE,
  MAX_TEMPERATURE,
  MIN_MAX_TOKENS,
  MAX_MAX_TOKENS,
  MAX_API_KEY_LENGTH,
} from '../validators/settingsValidator';
import { EXPECTED_ROUTE_DOMAINS } from '../routes/routeManifest';
import { Prisma } from '@prisma/client';
import { KnowledgeCategory } from '../services/systemKnowledge/types';

describe('System Knowledge Sync & Drift Guard', () => {
  it('exports valid validator constants and numeric bounds', () => {
    expect(MIN_TEMPERATURE).toBe(0);
    expect(MAX_TEMPERATURE).toBe(2);
    expect(MIN_MAX_TOKENS).toBe(100);
    expect(MAX_MAX_TOKENS).toBe(32000);
    expect(MAX_API_KEY_LENGTH).toBe(256);
    expect(ALLOWED_PROVIDERS).toEqual([
      'openai',
      'ollama',
      'gemini',
      'anthropic',
    ]);
    expect(ALLOWED_SETTINGS_FIELDS).toContain('default_provider');
    expect(ALLOWED_SETTINGS_FIELDS).toContain('openai_api_key');
    expect(ALLOWED_SETTINGS_FIELDS).toContain('clear_openai_api_key');
  });

  it('reads live metadata with runtime bounds', () => {
    const metadata = getLiveSystemMetadata();
    expect(metadata.allowedProviders).toEqual([...ALLOWED_PROVIDERS]);
    expect(metadata.temperatureRange).toEqual({
      min: MIN_TEMPERATURE,
      max: MAX_TEMPERATURE,
      default: 0.7,
    });
    expect(metadata.maxTokensRange).toEqual({
      min: MIN_MAX_TOKENS,
      max: MAX_MAX_TOKENS,
      default: 2000,
    });
    expect(metadata.maxUploadMb).toBeGreaterThan(0);
    expect(metadata.conversationMemoryMaxNotes).toBe(20);
    expect(metadata.conversationMemoryNoteMaxChars).toBe(500);
    expect(metadata.conversationSummaryThreshold).toBe(40);
    expect(metadata.userMemoryMaxNotes).toBe(30);
    expect(metadata.userMemoryNoteMaxChars).toBe(500);
    expect(Array.isArray(metadata.supportedPricingModels)).toBe(true);
    expect(metadata.supportedPricingModels.length).toBeGreaterThan(0);
  });

  it('provides curated cards covering all 7 knowledge categories in Ukrainian', () => {
    const cards = getCuratedKnowledgeCards();
    const categories = new Set(cards.map((c) => c.category));
    const expectedCategories: KnowledgeCategory[] = [
      'providers',
      'settings',
      'rag',
      'memory',
      'artifacts',
      'chat_tools',
      'desktop',
    ];

    for (const cat of expectedCategories) {
      expect(categories.has(cat)).toBe(true);
    }

    // All curated cards must have Ukrainian content and required fields
    const ukrainianRegex = /[\u0400-\u04FF]/;
    for (const card of cards) {
      expect(card.id).toBeTruthy();
      expect(card.title).toMatch(ukrainianRegex);
      expect(card.summary).toMatch(ukrainianRegex);
      expect(card.whyUse).toMatch(ukrainianRegex);
      expect(card.howToUse).toMatch(ukrainianRegex);
      expect(card.uiPath).toBeTruthy();
      expect(Array.isArray(card.keywords)).toBe(true);
      expect(card.keywords.length).toBeGreaterThan(0);
      expect(card.liveFacts).toBeDefined();

      // Ensure no raw keys or placeholder secrets are exposed
      const serialized = JSON.stringify(card);
      expect(serialized).not.toMatch(/sk-[a-zA-Z0-9]{20,}/);
      expect(serialized).not.toMatch(/AIza[a-zA-Z0-9_-]{30,}/);
    }
  });

  it('buildIntrospectedKnowledgeCatalog produces zero autoGenerated cards for current codebase', () => {
    const catalog = buildIntrospectedKnowledgeCatalog();

    expect(catalog.autoGenerated).toEqual([]);
    expect(catalog.cards.every((c) => !c.autoGenerated)).toBe(true);
    expect(catalog.versionHash).toMatch(/^[a-f0-9]{12}$/);
  });

  it('covers all Prisma UserSettings non-internal fields in curated cards', () => {
    const internalFields = new Set([
      'id',
      'userId',
      'createdAt',
      'updatedAt',
    ]);
    const prismaFields = Object.keys(Prisma.UserSettingsScalarFieldEnum).filter(
      (f) => !internalFields.has(f)
    );

    const cards = getCuratedKnowledgeCards();
    const allRelatedSettings = new Set(
      cards.flatMap((c) => c.relatedSettings || [])
    );

    for (const field of prismaFields) {
      expect(allRelatedSettings.has(field)).toBe(true);
    }
  });

  it('covers all ALLOWED_SETTINGS_FIELDS in curated cards', () => {
    const cards = getCuratedKnowledgeCards();
    const allRelatedSettings = new Set(
      cards.flatMap((c) => c.relatedSettings || [])
    );

    for (const field of ALLOWED_SETTINGS_FIELDS) {
      expect(allRelatedSettings.has(field)).toBe(true);
    }
  });

  it('covers all EXPECTED_ROUTE_DOMAINS in curated cards', () => {
    const cards = getCuratedKnowledgeCards();
    const allRelatedRoutes = new Set(
      cards.flatMap((c) => c.relatedRoutes || [])
    );

    for (const domain of EXPECTED_ROUTE_DOMAINS) {
      expect(allRelatedRoutes.has(domain)).toBe(true);
    }
  });

  it('covers all ALLOWED_PROVIDERS in curated cards', () => {
    const cards = getCuratedKnowledgeCards();
    const providerCardIds = new Set(cards.map((c) => c.id));

    for (const provider of ALLOWED_PROVIDERS) {
      expect(providerCardIds.has(`provider-${provider}`)).toBe(true);
    }
  });

  it('synthesizes auto-generated cards and changes versionHash when schema drifts', () => {
    const standardCatalog = buildIntrospectedKnowledgeCatalog();

    // Simulate extra settings field drift
    const driftSettingsCatalog = buildIntrospectedKnowledgeCatalog({
      extraSettingsFields: ['experimental_neural_search'],
    });

    expect(driftSettingsCatalog.autoGenerated.length).toBe(1);
    expect(driftSettingsCatalog.autoGenerated[0].id).toBe(
      'auto-setting-experimental_neural_search'
    );
    expect(driftSettingsCatalog.autoGenerated[0].autoGenerated).toBe(true);
    expect(driftSettingsCatalog.versionHash).not.toBe(
      standardCatalog.versionHash
    );

    // Simulate extra route domain drift
    const driftRouteCatalog = buildIntrospectedKnowledgeCatalog({
      extraRouteDomains: ['telemetry'],
    });

    expect(driftRouteCatalog.autoGenerated.length).toBe(1);
    expect(driftRouteCatalog.autoGenerated[0].id).toBe('auto-route-telemetry');
    expect(driftRouteCatalog.autoGenerated[0].autoGenerated).toBe(true);
    expect(driftRouteCatalog.versionHash).not.toBe(standardCatalog.versionHash);
  });

  it('computes deterministic 12-char SHA-256 version hashes', () => {
    const metadata = getLiveSystemMetadata();
    const cards = getCuratedKnowledgeCards();

    const hash1 = computeVersionHash(metadata, cards);
    const hash2 = computeVersionHash(metadata, cards);

    expect(hash1).toBe(hash2);
    expect(hash1.length).toBe(12);
  });
});
