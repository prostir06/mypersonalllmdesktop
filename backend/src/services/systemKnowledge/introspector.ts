import { createHash } from 'crypto';
import { Prisma } from '../../generated/prisma/client';
import { EXPECTED_ROUTE_DOMAINS } from '../../routes/routeManifest';
import {
  ALLOWED_PROVIDERS,
  ALLOWED_SETTINGS_FIELDS,
} from '../../validators/settingsValidator';
import { getLiveSystemMetadata } from './liveMetadata';
import { getCuratedKnowledgeCards } from './registry';
import type { KnowledgeCard, LiveSystemMetadata } from './types';

const INTERNAL_PRISMA_SETTINGS_FIELDS = new Set([
  'id',
  'userId',
  'createdAt',
  'updatedAt',
]);

export interface IntrospectorOptions {
  extraSettingsFields?: string[];
  extraRouteDomains?: string[];
  overridePrismaFields?: string[];
  overrideRouteDomains?: string[];
  overrideAllowedSettings?: string[];
  overrideAllowedProviders?: string[];
}

let processCatalog: IntrospectedCatalog | undefined;

/** Tests that change live metadata between calls. */
export function resetIntrospectedKnowledgeCatalog(): void {
  processCatalog = undefined;
}

export interface IntrospectedCatalog {
  metadata: LiveSystemMetadata;
  cards: KnowledgeCard[];
  versionHash: string;
  autoGenerated: KnowledgeCard[];
}

export function computeVersionHash(
  metadata: LiveSystemMetadata,
  cards: KnowledgeCard[]
): string {
  const payload = JSON.stringify({ metadata, cards });
  return createHash('sha256').update(payload).digest('hex').slice(0, 12);
}

function buildCatalogUncached(
  options?: IntrospectorOptions
): IntrospectedCatalog {
  const metadata = getLiveSystemMetadata();
  const cards = getCuratedKnowledgeCards();
  const autoGenerated: KnowledgeCard[] = [];

  const coveredSettings = new Set(
    cards.flatMap((c) => c.relatedSettings || [])
  );
  const coveredRoutes = new Set(cards.flatMap((c) => c.relatedRoutes || []));
  const coveredProviders = new Set(
    cards.filter((c) => c.category === 'providers').map((c) => c.id)
  );

  // 1. Settings introspection
  const prismaFields =
    options?.overridePrismaFields ??
    Object.keys(Prisma.UserSettingsScalarFieldEnum).filter(
      (f) => !INTERNAL_PRISMA_SETTINGS_FIELDS.has(f)
    );
  const validatorFields =
    options?.overrideAllowedSettings ?? [...ALLOWED_SETTINGS_FIELDS];
  const extraSettings = options?.extraSettingsFields ?? [];

  const allSettingsToCheck = Array.from(
    new Set([...prismaFields, ...validatorFields, ...extraSettings])
  );

  for (const setting of allSettingsToCheck) {
    if (!coveredSettings.has(setting)) {
      const card: KnowledgeCard = {
        id: `auto-setting-${setting}`,
        category: 'settings',
        title: `Налаштування: ${setting}`,
        summary: `Автоматично згенерована картка для налаштування ${setting}. Потребує кураторського опису.`,
        whyUse: `Використовується для конфігурації параметра ${setting}.`,
        howToUse: `Змініть значення ${setting} через API або інтерфейс налаштувань.`,
        uiPath: '/settings',
        relatedSettings: [setting],
        keywords: [setting, 'auto-generated', 'налаштування'],
        liveFacts: { field: setting, autoGenerated: true },
        autoGenerated: true,
      };
      autoGenerated.push(card);
      cards.push(card);
      coveredSettings.add(setting);
    }
  }

  // 2. Route domains introspection
  const routeDomainsToCheck = Array.from(
    new Set([
      ...(options?.overrideRouteDomains ?? [...EXPECTED_ROUTE_DOMAINS]),
      ...(options?.extraRouteDomains ?? []),
    ])
  );

  for (const domain of routeDomainsToCheck) {
    if (!coveredRoutes.has(domain)) {
      const card: KnowledgeCard = {
        id: `auto-route-${domain}`,
        category: 'chat_tools',
        title: `Маршрут: ${domain}`,
        summary: `Автоматично згенерована картка для домену маршрутів ${domain}. Потребує кураторського опису.`,
        whyUse: `Забезпечує доступ до API ${domain}.`,
        howToUse: `Використовуйте кінцеві точки /api/${domain}.`,
        uiPath: `/${domain}`,
        relatedRoutes: [domain],
        keywords: [domain, 'auto-generated', 'маршрут'],
        liveFacts: { domain, autoGenerated: true },
        autoGenerated: true,
      };
      autoGenerated.push(card);
      cards.push(card);
      coveredRoutes.add(domain);
    }
  }

  // 3. Providers introspection
  const providersToCheck =
    options?.overrideAllowedProviders ?? [...ALLOWED_PROVIDERS];
  for (const provider of providersToCheck) {
    const providerCardId = `provider-${provider}`;
    if (!coveredProviders.has(providerCardId)) {
      const card: KnowledgeCard = {
        id: providerCardId,
        category: 'providers',
        title: `Провайдер: ${provider}`,
        summary: `Автоматично згенерована картка для провайдера ${provider}. Потребує кураторського опису.`,
        whyUse: `Використовується для підключення моделей ${provider}.`,
        howToUse: `Налаштуйте параметри для ${provider} у меню налаштувань.`,
        uiPath: '/settings',
        relatedSettings: [`${provider}_api_key`],
        keywords: [provider, 'auto-generated', 'провайдер'],
        liveFacts: { provider, autoGenerated: true },
        autoGenerated: true,
      };
      autoGenerated.push(card);
      cards.push(card);
      coveredProviders.add(providerCardId);
    }
  }

  const versionHash = computeVersionHash(metadata, cards);

  return {
    metadata,
    cards,
    versionHash,
    autoGenerated,
  };
}

/** Catalog is static for the process unless a caller passes overrides. */
export function buildIntrospectedKnowledgeCatalog(
  options?: IntrospectorOptions
): IntrospectedCatalog {
  if (!options && processCatalog) return processCatalog;
  const catalog = buildCatalogUncached(options);
  if (!options) processCatalog = catalog;
  return catalog;
}
