export type KnowledgeCategory =
  | 'providers'
  | 'settings'
  | 'rag'
  | 'memory'
  | 'artifacts'
  | 'chat_tools'
  | 'desktop';

export interface KnowledgeCard {
  id: string;
  category: KnowledgeCategory;
  title: string;
  summary: string;
  whyUse: string;
  howToUse: string;
  uiPath: string;
  relatedSettings?: string[];
  relatedRoutes?: string[];
  keywords: string[];
  liveFacts: Record<string, string | number | boolean | string[]>;
  autoGenerated?: boolean;
}

export type AdvisoryActionType =
  | 'navigate_settings'
  | 'open_documents'
  | 'open_prompts'
  | 'ask_ai';

export interface AdvisoryTip {
  id: string;
  severity: 'warning' | 'info';
  category: KnowledgeCategory;
  title: string;
  message: string;
  actionLabel: string;
  actionType: AdvisoryActionType;
  actionTarget?: string;
  suggestedPrompt?: string;
}

export interface UserSystemSnapshot {
  activeProvider: string;
  activeModel: string;
  modelSupportsVision: boolean;
  modelSupportsWebSearch: boolean;
  webSearchEnabled: boolean;
  configuredProviders: {
    openai: boolean;
    gemini: boolean;
    anthropic: boolean;
    ollamaHost: string;
  };
  ragEmbeddingMode: 'openai' | 'ollama' | 'fallback';
  documents: {
    total: number;
    ready: number;
    pending: number;
    failed: number;
    needsReindex: number;
    selectedInChat: number;
  };
  hasCustomSystemPrompt: boolean;
  pinnedPromptsCount: number;
  userMemoryNotesCount: number;
  temperature: number;
  maxTokens: number;
}

export interface LiveSystemMetadata {
  allowedProviders: string[];
  temperatureRange: { min: number; max: number; default: number };
  maxTokensRange: { min: number; max: number; default: number };
  maxUploadMb: number;
  conversationMemoryMaxNotes: number;
  conversationMemoryNoteMaxChars: number;
  conversationSummaryThreshold: number;
  userMemoryMaxNotes: number;
  userMemoryNoteMaxChars: number;
  supportedPricingModels: string[];
}

export interface SystemKnowledgeResponse {
  versionHash: string;
  generatedAt: string;
  snapshot: UserSystemSnapshot;
  advisories: AdvisoryTip[];
  cards: KnowledgeCard[];
}
